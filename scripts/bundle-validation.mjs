#!/usr/bin/env node
// Bundles src/utils/editor/validation.ts (the single source of truth for
// exercise validation) into an IIFE string that is embedded in the exercise
// WebView. The module has no runtime dependencies, so the bundle stays small
// and the exact same code can be imported by the Node-side checks.
// Run via: npm run bundle-validation
import { execSync } from "child_process";
import fs from "fs";
import path from "path";

const MIN_BUNDLE_BYTES = 1_000;

function main() {
  const outFile = path.resolve("src/utils/editor/validation-core.generated.ts");
  const entry = path.resolve("src/utils/editor/validation.ts");
  const esbuild = path.resolve("node_modules/.bin/esbuild");

  if (!fs.existsSync(esbuild)) {
    console.error(
      `\nError: esbuild not found at ${esbuild}.\nRun "npm install" first, or install esbuild globally.\n`
    );
    process.exit(1);
  }

  const result = execSync(
    `"${esbuild}" "${entry}" --bundle --format=iife --global-name=__VAL_CORE --minify --platform=browser --target=es2020`,
    { encoding: "utf-8", maxBuffer: 50 * 1024 * 1024 }
  );

  const bundle = result.trim().replace(
    /var __VAL_CORE\s*=/,
    "globalThis.__VAL_CORE ="
  );

  if (bundle.length < MIN_BUNDLE_BYTES) {
    console.error(
      `\nError: validation bundle is too small (${bundle.length} bytes, expected >= ${MIN_BUNDLE_BYTES}).\n` +
        "esbuild may have failed to bundle dependencies. Check node_modules.\n"
    );
    process.exit(1);
  }

  const tsContent = `// Auto-generated by scripts/bundle-validation.mjs — DO NOT EDIT
export const VALIDATION_CORE = ${JSON.stringify(bundle)};
`;
  fs.writeFileSync(outFile, tsContent, "utf-8");
  console.log(`Validation bundle written to ${outFile} (${bundle.length} bytes)`);
}

main();
