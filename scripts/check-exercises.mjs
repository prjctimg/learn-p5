#!/usr/bin/env node
// Dev-only invariant: assert each task's validation rules are satisfiable
// against the task's solution and that all rules are well-formed.
// Uses the same shared core as the exercise WebView bridge so the
// validation semantics are identical in dev and runtime.
// Run via: npm run check-exercises
import fs from "fs";
import path from "path";
import jsyaml from "js-yaml";
import { parser } from "@lezer/javascript";

const COURSES_DIR = path.resolve("src/data/courses");
const REFERENCE_FILE = path.resolve("src/data/reference.generated.json");

// Load the shared validation core (generated by bundle-validation.mjs).
const corePath = path.resolve("src/utils/editor/validation-core.generated.ts");
const coreSrc = fs.readFileSync(corePath, "utf-8");
const coreMatch = coreSrc.match(/export const VALIDATION_CORE = (.+);/);
if (!coreMatch) {
  console.error(
    "Error: could not extract VALIDATION_CORE from validation-core.generated.ts.\n" +
      "Run npm run bundle-validation first."
  );
  process.exit(1);
}
const coreJs = JSON.parse(coreMatch[1]);
new Function(coreJs)();
const VC = globalThis.__VAL_CORE;

let p5Names = [];
try {
  const reference = JSON.parse(fs.readFileSync(REFERENCE_FILE, "utf8"));
  p5Names = Array.isArray(reference.functionNames) ? reference.functionNames : [];
} catch {
  console.error(
    `Error: could not read ${REFERENCE_FILE}.\n` +
      "Run npm run gen-reference first."
  );
  process.exit(1);
}
if (p5Names.length === 0) {
  console.error(`Error: no p5 function names found in ${REFERENCE_FILE}.`);
  process.exit(1);
}

function analyzeCode(code) {
  const tree = parser.parse(code);
  return VC.analyze({
    cursor: () => tree.cursor(),
    slice: (from, to) => code.slice(from, to),
  });
}

function evalRules(code, rules) {
  return VC.evaluateRules(analyzeCode(code), rules);
}

let failures = 0;

function checkExercise(ex) {
  if (!ex.tasks || ex.tasks.length === 0) return;
  const solution = ex.solution ?? "";

  for (let ti = 0; ti < ex.tasks.length; ti++) {
    const task = ex.tasks[ti];
    const isFinal = ti === ex.tasks.length - 1;
    const taskSolution = task.solution ?? (isFinal ? solution : "");

    // The shared core expects validation to be an array (see types.ts).
    if (!Array.isArray(task.validation)) {
      console.error(`  ✗ ${ex.id}/${task.id}: task.validation is missing or not an array`);
      failures++;
      continue;
    }

    // Schema check: catch malformed rules (typos, unknown types, missing fields)
    const schemaProblems = VC.schemaErrors(task.validation);
    for (const p of schemaProblems) {
      console.error(`  ✗ ${ex.id}/${task.id}: ${p}`);
      failures++;
    }

    if (!taskSolution) {
      console.error(`  ✗ ${ex.id}/${task.id}: task is missing a solution`);
      failures++;
      continue;
    }

    // Sync rules (functionCall, functionExists, canvasSize) are evaluated
    // by the shared core — identical logic to the exercise WebView bridge.
    const syncResult = evalRules(taskSolution, task.validation);
    if (!syncResult.passed) {
      console.error(
        `  ✗ ${ex.id}/${task.id}: solution fails ${syncResult.reason}`
      );
      failures++;
      continue;
    }

    // The task solution may only use p5 calls present in the solution,
    // starting code, or a functionCall rule.
    const allowed = new Set();
    const startingCode = task.startingCode ?? ex.startingCode ?? "";
    for (const code of [startingCode, taskSolution]) {
      for (const name of VC.p5CallNames(analyzeCode(code), p5Names)) {
        allowed.add(name);
      }
    }
    for (const rule of task.validation) {
      if (rule.type === "functionCall" && rule.name) allowed.add(rule.name);
    }
    const extra = VC.unexpectedCalls(analyzeCode(taskSolution), allowed, p5Names);
    if (extra.length > 0) {
      console.error(
        `  ✗ ${ex.id}/${task.id}: solution makes extra p5 calls: ${extra.join(", ")}`
      );
      failures++;
    }
  }
}

if (!fs.existsSync(COURSES_DIR)) {
  console.error(
    "Error: src/data/courses directory is missing. Course data must come from the downloadable content pack."
  );
  process.exit(1);
}

const yamlFiles = fs
  .readdirSync(COURSES_DIR)
  .filter((f) => f.endsWith(".yaml") || f.endsWith(".yml"));

for (const file of yamlFiles) {
  const yamlPath = path.join(COURSES_DIR, file);
  const raw = fs.readFileSync(yamlPath, "utf8");
  const data = jsyaml.load(raw);

  const course = data;
  console.log(`Checking course: ${course.slug}`);
  for (const ex of course.exercises ?? []) {
    checkExercise(ex);
  }
}

if (failures > 0) {
  console.error(`\n${failures} validation invariant failure(s).`);
  process.exit(1);
} else {
  console.log("\nAll exercise validation invariants OK.");
}