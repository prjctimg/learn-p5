#!/usr/bin/env node
// Fetches the latest published p5.js release and regenerates the vendored
// source artefacts:
//   - src/utils/p5Source.ts   (the minified p5 library as a string literal)
//   - src/utils/p5Version.ts  (the resolved version string)
//
// These files are gitignored build artefacts — regenerated on every fresh
// install and on `npm start` — so the app always bundles the newest p5.js.
// The format of p5Source.ts intentionally mirrors the original hand-authored
// shape (`const _p = [ ... ]; export const p5Source = _p.join("")`).

import fs from "fs";
import https from "https";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const P5_SOURCE_FILE = path.join(ROOT, "src/utils/p5Source.ts");
const P5_VERSION_FILE = path.join(ROOT, "src/utils/p5Version.ts");

function fetchText(url, redirects = 0) {
  return new Promise((resolve, reject) => {
    if (redirects > 10) return reject(new Error("Too many redirects"));
    https.get(url, { headers: { "User-Agent": "learn-p5-bundler" } }, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        res.resume();
        return resolve(fetchText(res.headers.location, redirects + 1));
      }
      if (res.statusCode !== 200) {
        res.resume();
        return reject(new Error(`HTTP ${res.statusCode} for ${url}`));
      }
      const chunks = [];
      res.setEncoding("utf8");
      res.on("data", (c) => chunks.push(c));
      res.on("end", () => resolve(chunks.join("")));
      res.on("error", reject);
    }).on("error", reject);
  });
}

async function getLatestVersion() {
  const txt = await fetchText("https://registry.npmjs.org/p5/latest");
  const data = JSON.parse(txt);
  if (!data.version) throw new Error("No version field in npm registry response");
  return data.version;
}

function escapeForDoubleQuotedString(s) {
  // We emit the source as a JS double-quoted string literal. Escape in an
  // order that avoids double-escaping: backslashes first, then real control
  // chars that would otherwise break the literal across lines, then quotes.
  return s
    .replace(/\\/g, "\\\\")
    .replace(/\r/g, "\\r")
    .replace(/\n/g, "\\n")
    .replace(/"/g, '\\"');
}

// Split the (potentially huge) minified source into a few array elements so
// the generated file stays diff-friendly and avoids pathological single-line
// lengths that choke some tooling.
function chunkSource(src, chunkSize = 200_000) {
  const chunks = [];
  for (let i = 0; i < src.length; i += chunkSize) {
    chunks.push(src.slice(i, i + chunkSize));
  }
  return chunks;
}

function writeP5Source(version, src) {
  const escaped = chunkSource(src).map((c) => `"${escapeForDoubleQuotedString(c)}"`);
  const body = escaped.join(",\n  ");
  const file =
    `// AUTO-GENERATED by scripts/bundle-p5.mjs — do not edit directly.\n` +
    `// p5.js v${version} — fetched from the npm registry (latest) at build time.\n` +
    `// Source: https://cdn.jsdelivr.net/npm/p5@${version}/lib/p5.min.js\n\n` +
    `const _p = [\n  ${body}\n];\n\n` +
    `export const p5Source: string = _p.join("");\n`;
  fs.writeFileSync(P5_SOURCE_FILE, file, "utf-8");
}

function writeP5Version(version) {
  const file =
    `// AUTO-GENERATED by scripts/bundle-p5.mjs — do not edit directly.\n` +
    `export const p5Version = "${version}";\n`;
  fs.writeFileSync(P5_VERSION_FILE, file, "utf-8");
}

async function main() {
  const version = await getLatestVersion();
  console.log(`[bundle-p5] Latest p5.js version: ${version}`);
  const url = `https://cdn.jsdelivr.net/npm/p5@${version}/lib/p5.min.js`;
  console.log(`[bundle-p5] Fetching ${url}`);
  const src = await fetchText(url);
  if (!src || src.length < 100_000) {
    throw new Error(`Fetched p5 source looks empty/too small (${src?.length ?? 0} bytes)`);
  }
  writeP5Source(version, src);
  writeP5Version(version);
  console.log(`[bundle-p5] Wrote ${P5_SOURCE_FILE} (${src.length} bytes)`);
  console.log(`[bundle-p5] Wrote ${P5_VERSION_FILE}`);
}

main().catch((err) => {
  console.error("[bundle-p5] FAILED:", err);
  process.exit(1);
});