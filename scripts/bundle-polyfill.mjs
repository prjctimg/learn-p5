#!/usr/bin/env node
// Bundles core-js/stable polyfills for the preview WebViews. This is
// the only polyfill layer: JS built-ins come from core-js (the
// maintained polyfill library), and DOM APIs (AbortController,
// Element.remove/closest, TextEncoder, etc.) are native in the
// targeted modern WebView (Baseline, Chrome 90+ / iOS 16.4+).
// No hand-written shims; p5 itself is fetched verbatim by
// scripts/bundle-p5.mjs (no custom transpilation).
// Run via: npm run bundle-polyfill
import { execSync } from "child_process";
import fs from "fs";
import path from "path";

const MIN_BUNDLE_BYTES = 100_000;

function main() {
  const outFile = path.resolve("src/utils/editor/polyfill.generated.ts");
  const entry = path.resolve("src/utils/editor/bundlePolyfillEntry.ts");
  const esbuild = path.resolve("node_modules/.bin/esbuild");

  if (!fs.existsSync(esbuild)) {
    console.error(
      `\nError: esbuild not found at ${esbuild}.\nRun "npm install" first, or install esbuild globally.\n`
    );
    process.exit(1);
  }

  const result = execSync(
    `"${esbuild}" "${entry}" --bundle --format=iife --minify --platform=browser --target=es2020 --charset=utf8`,
    { encoding: "utf-8", maxBuffer: 100 * 1024 * 1024 }
  );

  const bundle = result.trim();

  if (bundle.length < MIN_BUNDLE_BYTES) {
    console.error(
      `\nError: Polyfill bundle is too small (${bundle.length} bytes, expected >= ${MIN_BUNDLE_BYTES}).\n` +
        "esbuild may have failed to bundle core-js. Check node_modules.\n"
    );
    process.exit(1);
  }

  const tsContent = `// Auto-generated by scripts/bundle-polyfill.mjs — DO NOT EDIT
export const CORE_JS_VERSION = ${JSON.stringify("3.51.0")};
export const CORE_JS_BUNDLE = ${JSON.stringify(bundle)};
`;
  fs.writeFileSync(outFile, tsContent, "utf-8");
  console.log(`Polyfill bundle written to ${outFile} (${bundle.length} bytes)`);
}

main();
